#!/usr/bin/env python3
"""Generate deploy/k8s/base/ergo/ircd.yaml from Ergo's stock default.yaml plus trough's changes.

Usage: docker run --rm --entrypoint cat ghcr.io/ergochat/ergo:stable /ircd-bin/default.yaml \
         | scripts/gen-ergo-config.py > deploy/k8s/base/ergo/ircd.yaml

Why a generated file and not ERGO__ env overrides: Ergo silently fails to apply several
nested overrides (ip-limits, login-throttling, registration throttling), which then
throttles the steward server's many connections.
"""
import sys
import yaml

cfg = yaml.safe_load(sys.stdin)
s, a = cfg["server"], cfg["accounts"]

cfg["network"]["name"] = "trough"
s["name"] = "trough.local"
# Absolute paths: config is mounted read-only at /config, state lives in /ircd.
s["listeners"] = {":6667": None, ":6697": {"tls": {"cert": "/ircd/fullchain.pem", "key": "/ircd/privkey.pem"}, "min-tls-version": 1.2}}
s["motd"] = "/config/ergo.motd"
# Many bot connections from one pod IP / NAT gateway.
s["ip-limits"]["count"] = False
s["ip-limits"]["throttle"] = False
s["ip-cloaking"]["enabled"] = False
# Sessions are <principal>|<handle> nicks all logged in to the principal's account.
a["nick-reservation"]["enabled"] = False
a["nick-reservation"]["force-nick-equals-account"] = False
a["registration"]["throttling"]["enabled"] = False
a["login-throttling"]["enabled"] = False
cfg["fakelag"]["enabled"] = False
cfg["datastore"]["path"] = "/ircd/ircd.db"
cfg["lock-file"] = "/ircd/ircd.lock"
cfg["languages"]["path"] = "/ircd-bin/languages"
# Bump history so CHATHISTORY catch-up covers a working day of #trough.
cfg["history"]["channel-length"] = 4096
# The stock oper password hash is a placeholder nobody knows, i.e. opers are disabled.
# Set one with `ergo genpasswd` if you need /OPER (e.g. NickServ SAREGISTER on closed servers).

sys.stdout.write("# GENERATED by scripts/gen-ergo-config.py from Ergo's default.yaml. Edit the script, not this file.\n")
yaml.safe_dump(cfg, sys.stdout, sort_keys=False, default_flow_style=False)
